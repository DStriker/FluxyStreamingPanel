using Fluxy.Core.Content.Enums;
using Fluxy.Core.Requests.Enums;

namespace Fluxy.Core.Requests.Commands
{
    /// <summary>
    /// Values one API request failure row is written with, before it has an identifier.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>Its only caller is the Development trial seeder.</b> The capture path that will record
    /// real refusals belongs to the future public API and arrives with its own command and its
    /// own rules - which request was refused and why - so this type deliberately carries nothing
    /// but the stored columns.
    /// </para>
    /// <para>
    /// The identifier and the audit timestamps are absent for the reason every other
    /// <c>New*</c> command omits them: the first is generated by the row, and the second are the
    /// context's to stamp.
    /// </para>
    /// </remarks>
    public sealed record NewApiRequestFailure
    {
        /// <summary>Free-form access parameter the refused request named, or null.</summary>
        public string? SubscriptionData { get; init; }

        /// <summary>Kind of the content the request named, or null when it named none.</summary>
        public ContentType? ContentKind { get; init; }

        /// <summary>Opaque identifier of that content, or null.</summary>
        public Guid? ContentId { get; init; }

        /// <summary>Name of that content as it read at write time, or null.</summary>
        public string? ContentName { get; init; }

        /// <summary>Why the request was refused.</summary>
        public required ApiRequestFailureReason Reason { get; init; }

        /// <summary>Address the request came from.</summary>
        public required string Ip { get; init; }

        /// <summary>Internet provider the address belonged to, or null.</summary>
        public string? Isp { get; init; }

        /// <summary>Upper-case ISO 3166-1 alpha-2 country of the address, or null.</summary>
        public string? CountryCode { get; init; }

        /// <summary>English sentence describing the refusal.</summary>
        public required string Description { get; init; }
    }
}
