namespace Fluxy.Core.Abstractions
{
    /// <summary>
    /// Raised when the database refused a write because a unique index would have been
    /// violated, and carries which index refused.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The point of the type is the name it carries. PostgreSQL answers every unique refusal
    /// with the same <c>SQLSTATE</c> and the index that produced it, and only the caller knows
    /// which of its indexes it can explain: a service that answers <i>every</i> collision as
    /// "that name is already taken" turns a bug in its own list writer into a confidently wrong
    /// answer, which is a mistake this codebase has already made once. So the infrastructure
    /// reports the fact and the caller asks about the index it knows with
    /// <see cref="IsConstraint"/>.
    /// </para>
    /// <para>
    /// It lives in <c>Fluxy.Core</c> even though it is raised by the data layer: a service that
    /// catches it must not need to reference the provider or the context, and the name of an
    /// index is plain text rather than an infrastructure type.
    /// </para>
    /// </remarks>
    public sealed class UniqueViolationException : Exception
    {
        /// <summary>
        /// Initializes a new instance of the <see cref="UniqueViolationException"/> class.
        /// </summary>
        /// <param name="constraintName">Name of the index that refused the write, or null when
        /// the database did not name one.</param>
        /// <param name="innerException">The database failure this was read from.</param>
        public UniqueViolationException(string? constraintName, Exception? innerException)
            : base(
                constraintName is null
                    ? "A unique index refused the write."
                    : $"A unique index refused the write: {constraintName}.",
                innerException)
        {
            ConstraintName = constraintName;
        }

        /// <summary>
        /// Name of the unique index that refused the write. Null only when the database did not
        /// name one, which <see cref="IsConstraint"/> answers false for.
        /// </summary>
        public string? ConstraintName { get; }

        /// <summary>
        /// Whether the refused index is <paramref name="constraintName"/>.
        /// </summary>
        /// <remarks>
        /// Compared exactly and case sensitively: index names are generated by the model and
        /// compared against constants written from the migrations, and a "close enough" match
        /// here would let the wrong index answer for the right one.
        /// </remarks>
        public bool IsConstraint(string constraintName)
            => ConstraintName is not null
                && string.Equals(ConstraintName, constraintName, StringComparison.Ordinal);
    }
}
