using Fluxy.Core.Subscriptions.Enums;

namespace Fluxy.Core.Subscriptions.Commands
{
    /// <summary>
    /// The values one MAG event row is actually written with, after the send rules resolved every
    /// flag and normalised the message.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>A separate type from <see cref="NewMagEvent"/> on purpose.</b> The request carries
    /// nullable flags because "not sent" and "sent false" are different requests; this type carries
    /// resolved booleans, because the database must never invent a value for a column the
    /// application forgot - the rule that keeps <c>HasDefaultValue</c> out of every configuration.
    /// Only <c>MagEventRules</c> produces it, so the defaults live in exactly one place.
    /// </para>
    /// <para>
    /// The identifier and the audit timestamps are absent for the reason every other <c>*Write</c>
    /// command omits them: the first is generated by the row, and the second are the context's to
    /// stamp.
    /// </para>
    /// </remarks>
    public sealed record MagEventWrite
    {
        /// <summary>The subscription the event is sent under.</summary>
        public required Guid SubscriptionId { get; init; }

        /// <summary>Which operation the row records.</summary>
        public required MagEventType EventType { get; init; }

        /// <summary>Stored payload - a message text, a stream identifier, or null.</summary>
        public string? Message { get; init; }

        /// <summary>Whether the device must confirm the operation.</summary>
        public required bool NeedConfirm { get; init; }

        /// <summary>Whether the device should reboot after a successful operation.</summary>
        public required bool RebootAfterOk { get; init; }

        /// <summary>Whether the message hides itself after a timeout.</summary>
        public required bool AutoHideTimeout { get; init; }

        /// <summary>Whether other services are switched on with the operation.</summary>
        public required bool AdditionalServicesOn { get; init; }

        /// <summary>ANEC flag.</summary>
        public required bool Anec { get; init; }

        /// <summary>VCLUB flag.</summary>
        public required bool Vclub { get; init; }
    }
}
