using Fluxy.Core.Subscriptions.Enums;

namespace Fluxy.Core.Subscriptions.Commands
{
    /// <summary>
    /// Values one connection log row is written with, before it has an identifier.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>Its only caller is the Development trial seeder.</b> The capture path that the relaying
    /// process will own arrives with its own command and its own rules - which allowance was
    /// spent, which session opened the connection - so this type deliberately carries nothing but
    /// the stored columns.
    /// </para>
    /// <para>
    /// The identifier and the audit timestamps are absent for the reason every other
    /// <c>New*</c> command omits them: the first is generated by the row, and the second are the
    /// context's to stamp.
    /// </para>
    /// </remarks>
    public sealed record NewConnectionLog
    {
        /// <summary>The subscription the connection was made under.</summary>
        public required Guid SubscriptionId { get; init; }

        /// <summary>Which medium it delivered.</summary>
        public required ConnectionStreamKind StreamKind { get; init; }

        /// <summary>Opaque identifier of the stream it delivered.</summary>
        public required Guid StreamId { get; init; }

        /// <summary>Address the session came from.</summary>
        public required string Ip { get; init; }

        /// <summary>User agent the session presented, or null.</summary>
        public string? UserAgent { get; init; }

        /// <summary>Upper-case ISO 3166-1 alpha-2 country of the address, or null.</summary>
        public string? CountryCode { get; init; }

        /// <summary>Internet provider the address belongs to, or null.</summary>
        public string? Isp { get; init; }

        /// <summary>When the session opened.</summary>
        public required DateTimeOffset StartedAt { get; init; }

        /// <summary>When it finished, or null while it is still live.</summary>
        public DateTimeOffset? EndedAt { get; init; }

        /// <summary>Process identifier the broadcasting side reported, or null.</summary>
        public int? BroadcastPid { get; init; }
    }
}
