namespace Fluxy.Core.Users.Models
{
    /// <summary>
    /// Immutable business representation of one entry of a reseller's credit ledger: the balance
    /// moved by this row, when, by whom, and why in English words.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>The amount is a signed delta, not a balance.</b> A positive value is credit issued, a
    /// negative value is credit spent, and the table never stores the running total - the balance
    /// lives on <c>users.credits</c> and this row says how one change of it came about. A row of
    /// zero is possible and deliberate: it is the entry an account created with no initial credit
    /// carries, so even a reseller handed nothing has one line of audit that says so.
    /// </para>
    /// <para>
    /// <b><see cref="IssuedById"/> names the administrator who wrote the row.</b> Every row the
    /// admin panel writes - a create, or an update that raises or lowers the balance - carries the
    /// acting administrator. It is null on a reseller-spent row (a write path that does not exist
    /// yet) and after the issuing administrator's account is deleted.
    /// </para>
    /// <para>
    /// <b><see cref="ResellerId"/> cascades.</b> A ledger line whose subject no longer exists is
    /// a line nobody can be told about, so deleting an account deletes its credit log with it -
    /// the same rule the connection log follows for its subscription.
    /// </para>
    /// </remarks>
    public sealed record CreditLog
    {
        /// <summary>Identifier of the ledger entry.</summary>
        public required Guid Id { get; init; }

        /// <summary>Reseller whose balance this row moved. Removed with the account.</summary>
        public required Guid ResellerId { get; init; }

        /// <summary>
        /// Administrator who wrote this row in the admin panel, for a create or an update of
        /// either sign; null on a reseller-spent row and after the issuing administrator is
        /// deleted.
        /// </summary>
        public Guid? IssuedById { get; init; }

        /// <summary>
        /// Signed change to the balance. Positive is credit issued, negative is credit spent,
        /// and zero is the entry an account created with no initial credit carries.
        /// </summary>
        public required int Amount { get; init; }

        /// <summary>English sentence describing the change, generated by the write path.</summary>
        public required string Description { get; init; }

        /// <summary>Creation timestamp of the row.</summary>
        public required DateTimeOffset CreatedAt { get; init; }

        /// <summary>Last modification timestamp of the row.</summary>
        public required DateTimeOffset UpdatedAt { get; init; }
    }
}
