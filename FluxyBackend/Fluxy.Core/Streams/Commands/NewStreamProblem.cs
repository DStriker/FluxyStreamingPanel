namespace Fluxy.Core.Streams.Commands
{
    /// <summary>
    /// Values one stream problem row is written with, before it has an identifier.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>Its production caller is the stream producer.</b> The producer knows which stream failed
    /// and what the failure said; this command carries exactly those two facts and nothing about
    /// how the row is stored.
    /// </para>
    /// <para>
    /// The identifier and the audit timestamps are absent for the reason every other
    /// <c>New*</c> command omits them: the first is generated by the row, and the second are the
    /// context's to stamp.
    /// </para>
    /// </remarks>
    public sealed record NewStreamProblem
    {
        /// <summary>Configured stream the problem is about.</summary>
        public required Guid StreamId { get; init; }

        /// <summary>Failure message as the producer reported it, before trimming or truncation.</summary>
        public required string ErrorMessage { get; init; }
    }
}
