namespace Fluxy.Core.Tickets.Commands
{
    /// <summary>
    /// Values one support ticket is opened with: the account that owns the conversation and the
    /// subject line it is filed under.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>The opening message is not part of this command.</b> The wire contract of the create
    /// endpoint carries a subject and nothing else; the visitor writes the first message in the
    /// thread they are taken to, where the conversation is. A ticket therefore starts with an
    /// empty thread, and the list's <c>lastReplyAt</c> falls back to its creation instant until
    /// somebody answers.
    /// </para>
    /// <para>
    /// The identifier and the audit timestamps are absent for the reason every other
    /// <c>New*</c> command omits them: the first is generated by the row, and the second are the
    /// context's to stamp.
    /// </para>
    /// </remarks>
    public sealed record NewTicket
    {
        /// <summary>Account that opens the ticket and owns the conversation.</summary>
        public required Guid UserId { get; init; }

        /// <summary>Subject line as the account typed it, before trimming.</summary>
        public required string Subject { get; init; }
    }
}
