using Fluxy.Core.Content.Enums;
using Fluxy.Core.Persistence.Base;
using Fluxy.Core.Requests.Enums;
using Fluxy.Core.Requests.Models;

namespace Fluxy.DataAccess.Entities
{
    /// <summary>
    /// Database representation of one refused public-API request. It is mutable, has no behaviour
    /// beyond mapping to <see cref="ApiRequestFailure"/>, and knows nothing about HTTP.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>The subscription data is opaque text, not a foreign key.</b> The public API receives it
    /// as a free-form access parameter, and a request naming an identifier this installation has
    /// no subscription for is exactly the refusal the row records. A foreign key would refuse the
    /// row the log exists to keep.
    /// </para>
    /// <para>
    /// <b>The content snapshot carries no foreign keys either.</b> <see cref="ContentId"/> may
    /// name content this installation never recorded, and <see cref="ContentName"/> is captured at
    /// write time so the row stays legible after the content is deleted. Nothing on the read path
    /// joins a content table or resolves a name.
    /// </para>
    /// <para>
    /// <b>There is no production write path.</b> The row is read and the whole table is cleared;
    /// the only insert is the Development seeder's, through the repository's staged
    /// <c>AddRangeAsync</c>. The future public API will own the real capture.
    /// </para>
    /// </remarks>
    public sealed class ApiRequestFailureEntity : AuditableEntity
    {
        /// <summary>
        /// Initializes a new instance of the <see cref="ApiRequestFailureEntity"/> class for a row
        /// that is about to be inserted. The identifier is generated by the base class and both
        /// audit timestamps are stamped by the context.
        /// </summary>
        public ApiRequestFailureEntity()
        {
        }

        /// <summary>
        /// Free-form access parameter the refused request named, up to 512 characters, or null.
        /// Deliberately not a subscription foreign key.
        /// </summary>
        public string? SubscriptionData { get; set; }

        /// <summary>Kind of the content the request named, or null, as a <c>smallint</c>.</summary>
        public ContentType? ContentKind { get; set; }

        /// <summary>Opaque identifier of that content, or null; deliberately not a foreign key.</summary>
        public Guid? ContentId { get; set; }

        /// <summary>Name of that content as it read at write time, up to 255 characters, or null.</summary>
        public string? ContentName { get; set; }

        /// <summary>Why the request was refused, stored as a <c>smallint</c>.</summary>
        public ApiRequestFailureReason Reason { get; set; }

        /// <summary>Address the request came from, up to 45 characters.</summary>
        public string Ip { get; set; } = string.Empty;

        /// <summary>Internet provider the address belonged to, up to 255 characters, or null.</summary>
        public string? Isp { get; set; }

        /// <summary>Upper-case ISO alpha-2 country of the address, or null when unknown.</summary>
        public string? CountryCode { get; set; }

        /// <summary>English sentence describing the refusal, up to 1000 characters.</summary>
        public string Description { get; set; } = string.Empty;

        /// <summary>Builds the business model out of this row.</summary>
        /// <remarks>
        /// <b>Reserved for the future capture path, which is why nothing calls it today.</b> The
        /// repository in this pass is read, clear and one insert intent the Development seeder
        /// uses, so no production read and no endpoint reaches this method. It stays beside
        /// <see cref="FromModel"/> because the write path that arrives with the public API will
        /// need the same pair every other entity here carries, and a mapping written then would be
        /// a second opinion about what the columns mean. It is deliberately not wired into a write
        /// path ahead of that caller.
        /// </remarks>
        public ApiRequestFailure ToModel() => new()
        {
            Id = Id,
            SubscriptionData = SubscriptionData,
            ContentKind = ContentKind,
            ContentId = ContentId,
            ContentName = ContentName,
            Reason = Reason,
            Ip = Ip,
            Isp = Isp,
            CountryCode = CountryCode,
            Description = Description,
            CreatedAt = CreatedAt,
            UpdatedAt = UpdatedAt
        };

        /// <summary>
        /// Copies the changeable fields of the business model onto this row.
        /// </summary>
        /// <remarks>
        /// <b>Reserved for the future capture path, which is why nothing calls it today.</b> The
        /// identifier and the audit timestamps are absent, because the first belongs to the row the
        /// tracker is holding and the second are the context's to stamp. No production endpoint and
        /// no read path reaches this method in this pass; it is kept so the capture that arrives
        /// with the public API uses the same mapping as <see cref="ToModel"/> rather than writing a
        /// second, divergent one.
        /// </remarks>
        public void FromModel(ApiRequestFailure model)
        {
            SubscriptionData = model.SubscriptionData;
            ContentKind = model.ContentKind;
            ContentId = model.ContentId;
            ContentName = model.ContentName;
            Reason = model.Reason;
            Ip = model.Ip;
            Isp = model.Isp;
            CountryCode = model.CountryCode;
            Description = model.Description;
        }
    }
}
