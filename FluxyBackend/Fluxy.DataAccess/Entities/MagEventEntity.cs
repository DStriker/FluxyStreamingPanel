using Fluxy.Core.Persistence.Base;
using Fluxy.Core.Subscriptions.Commands;
using Fluxy.Core.Subscriptions.Enums;
using Fluxy.Core.Subscriptions.Models;

namespace Fluxy.DataAccess.Entities
{
    /// <summary>
    /// Database representation of one event sent to a MAG device. It is mutable, has no behaviour
    /// beyond mapping to <see cref="MagEvent"/>, and knows nothing about HTTP.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>The subscription is a cascade foreign key.</b> An event without the subscription it was
    /// sent under is a row nobody can be told about, so deleting a subscription deletes its events.
    /// That consequence is intended: the journal is evidence about a subscription, and evidence
    /// whose subject is gone is what an operator asked to remove.
    /// </para>
    /// <para>
    /// <b>Every flag is a required column with no database default.</b> The values come from
    /// <c>MagEventRules</c>, resolved in the service, because a value the database invented for a
    /// column the application forgot would hide the mistake instead of surfacing it.
    /// </para>
    /// </remarks>
    public sealed class MagEventEntity : AuditableEntity
    {
        /// <summary>
        /// Initializes a new instance of the <see cref="MagEventEntity"/> class for a row that is
        /// about to be inserted. The identifier is generated by the base class and both audit
        /// timestamps are stamped by the context.
        /// </summary>
        public MagEventEntity()
        {
        }

        /// <summary>The subscription the event was sent under. Removed with it.</summary>
        public Guid SubscriptionId { get; set; }

        /// <summary>Which operation it asked for, as a <c>smallint</c>.</summary>
        public MagEventType EventType { get; set; }

        /// <summary>Operation payload - a message text, a stream identifier, or null.</summary>
        public string? Message { get; set; }

        /// <summary>Whether the device has confirmed the operation, as a <c>smallint</c>.</summary>
        public MagEventStatus Status { get; set; }

        /// <summary>Whether the device must confirm the operation.</summary>
        public bool NeedConfirm { get; set; }

        /// <summary>Whether the device should reboot after a successful operation.</summary>
        public bool RebootAfterOk { get; set; }

        /// <summary>Whether the message hides itself after a timeout.</summary>
        public bool AutoHideTimeout { get; set; }

        /// <summary>Whether other services are switched on with the operation.</summary>
        public bool AdditionalServicesOn { get; set; }

        /// <summary>ANEC flag.</summary>
        public bool Anec { get; set; }

        /// <summary>VCLUB flag.</summary>
        public bool Vclub { get; set; }

        /// <summary>Builds the business model out of this row.</summary>
        public MagEvent ToModel() => new()
        {
            Id = Id,
            SubscriptionId = SubscriptionId,
            EventType = EventType,
            Message = Message,
            Status = Status,
            NeedConfirm = NeedConfirm,
            RebootAfterOk = RebootAfterOk,
            AutoHideTimeout = AutoHideTimeout,
            AdditionalServicesOn = AdditionalServicesOn,
            Anec = Anec,
            Vclub = Vclub,
            CreatedAt = CreatedAt,
            UpdatedAt = UpdatedAt
        };

        /// <summary>
        /// Copies the changeable fields of the business model onto this row.
        /// </summary>
        /// <remarks>
        /// The identifier and the audit timestamps are absent, because the first belongs to the row
        /// the tracker is holding and the second are the context's to stamp.
        /// </remarks>
        public void FromModel(MagEvent model)
        {
            SubscriptionId = model.SubscriptionId;
            EventType = model.EventType;
            Message = model.Message;
            Status = model.Status;
            NeedConfirm = model.NeedConfirm;
            RebootAfterOk = model.RebootAfterOk;
            AutoHideTimeout = model.AutoHideTimeout;
            AdditionalServicesOn = model.AdditionalServicesOn;
            Anec = model.Anec;
            Vclub = model.Vclub;
        }

        /// <summary>
        /// Builds a fresh row out of the values a send resolved.
        /// </summary>
        /// <param name="write">Resolved row values.</param>
        /// <remarks>
        /// The status is <see cref="MagEventStatus.NotConfirmed"/> because a sent event has not
        /// been acknowledged yet - the confirmation path is the future streaming subsystem's.
        /// </remarks>
        public static MagEventEntity FromWrite(MagEventWrite write) => new()
        {
            SubscriptionId = write.SubscriptionId,
            EventType = write.EventType,
            Message = write.Message,
            Status = MagEventStatus.NotConfirmed,
            NeedConfirm = write.NeedConfirm,
            RebootAfterOk = write.RebootAfterOk,
            AutoHideTimeout = write.AutoHideTimeout,
            AdditionalServicesOn = write.AdditionalServicesOn,
            Anec = write.Anec,
            Vclub = write.Vclub
        };
    }
}
