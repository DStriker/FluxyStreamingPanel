using Fluxy.Core.Persistence.Base;
using Fluxy.Core.Tickets.Enums;
using Fluxy.Core.Tickets.Models;

namespace Fluxy.DataAccess.Entities
{
    /// <summary>
    /// Database representation of one support ticket. It is mutable, has no behaviour beyond
    /// mapping to <see cref="Ticket"/>, and knows nothing about HTTP.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>The account is a real foreign key that cascades.</b> A ticket is a conversation one
    /// account opened, so deleting the account deletes its tickets and, through the messages'
    /// own cascade, the conversation with them. No login name is stored: the operator's list
    /// resolves the name through a join on read, so a renamed account keeps drawing its current
    /// name.
    /// </para>
    /// <para>
    /// <b>The two flags are the two sides' unread state.</b> They live on this row rather than
    /// being derived from the messages on every read, because the list needs "is this unread for
    /// me" once per ticket and a derived answer would be a correlated subquery per row. The
    /// service raises and clears them; the row only stores them.
    /// </para>
    /// </remarks>
    public sealed class TicketEntity : AuditableEntity
    {
        /// <summary>
        /// Initializes a new instance of the <see cref="TicketEntity"/> class for a ticket that is
        /// about to be inserted. The identifier is generated by the base class and both audit
        /// timestamps are stamped by the context.
        /// </summary>
        public TicketEntity()
        {
        }

        /// <summary>Account that opened the ticket and owns the conversation.</summary>
        public Guid UserId { get; set; }

        /// <summary>Subject line, up to 200 characters.</summary>
        public string Subject { get; set; } = string.Empty;

        /// <summary>Lifecycle of the conversation, stored as a smallint.</summary>
        public TicketStatus Status { get; set; } = TicketStatus.Open;

        /// <summary>Whether the operator has a message it has not read yet.</summary>
        public bool AdminUnread { get; set; }

        /// <summary>Whether the account has a message it has not read yet.</summary>
        public bool UserUnread { get; set; }

        /// <summary>The messages of the conversation, deleted with it.</summary>
        public ICollection<TicketReplyEntity> Replies { get; set; } = new List<TicketReplyEntity>();

        /// <summary>Builds the business model out of this row.</summary>
        public Ticket ToModel() => new()
        {
            Id = Id,
            UserId = UserId,
            Subject = Subject,
            Status = Status,
            AdminUnread = AdminUnread,
            UserUnread = UserUnread,
            CreatedAt = CreatedAt,
            UpdatedAt = UpdatedAt
        };

        /// <summary>
        /// Copies the changeable fields of the business model onto this row.
        /// </summary>
        /// <remarks>
        /// The identifier and the audit timestamps are absent, because the first belongs to the row
        /// the tracker is holding and the second are the context's to stamp.
        /// </remarks>
        public void FromModel(Ticket model)
        {
            UserId = model.UserId;
            Subject = model.Subject;
            Status = model.Status;
            AdminUnread = model.AdminUnread;
            UserUnread = model.UserUnread;
        }
    }
}
