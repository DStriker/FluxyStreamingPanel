using Fluxy.Core.Persistence.Base;
using Fluxy.Core.Streams.Models;

namespace Fluxy.DataAccess.Entities
{
    /// <summary>
    /// Database representation of one problem a stream producer reported. It is mutable, has no
    /// behaviour beyond mapping to <see cref="StreamProblem"/>, and knows nothing about HTTP.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>The stream is a real foreign key.</b> A problem is evidence about one configured stream,
    /// so deleting the stream deletes its problems - the journal is about that stream, and a
    /// problem whose subject is gone is what an operator asked to remove. No stream name is
    /// stored: the name is resolved through the join when a page is read, so the list never shows a
    /// stale name.
    /// </para>
    /// <para>
    /// <b>The producer writes this table.</b> The process that plays a channel records what failed
    /// here; this pass has the storage, the reader, the clear and a Development seeder, and no HTTP
    /// write path.
    /// </para>
    /// </remarks>
    public sealed class StreamProblemEntity : AuditableEntity
    {
        /// <summary>
        /// Initializes a new instance of the <see cref="StreamProblemEntity"/> class for a row that
        /// is about to be inserted. The identifier is generated by the base class and both audit
        /// timestamps are stamped by the context.
        /// </summary>
        public StreamProblemEntity()
        {
        }

        /// <summary>Configured stream the problem is about. Removed with it.</summary>
        public Guid StreamId { get; set; }

        /// <summary>Reported failure message, up to 1000 characters.</summary>
        public string ErrorMessage { get; set; } = string.Empty;

        /// <summary>Builds the business model out of this row.</summary>
        /// <remarks>
        /// <b>Reserved for the future producer, which is why nothing calls it today.</b> The write
        /// path is <c>StreamProblemService.RecordAsync</c>, which maps the command onto a fresh row
        /// directly; this method stays beside <see cref="FromModel"/> so the producer that reads a
        /// problem back uses the same mapping every other entity here carries rather than writing a
        /// second opinion about what the columns mean.
        /// </remarks>
        public StreamProblem ToModel() => new()
        {
            Id = Id,
            StreamId = StreamId,
            ErrorMessage = ErrorMessage,
            CreatedAt = CreatedAt,
            UpdatedAt = UpdatedAt
        };

        /// <summary>
        /// Copies the changeable fields of the business model onto this row.
        /// </summary>
        /// <remarks>
        /// <b>Reserved for the future producer, which is why nothing calls it today.</b> The
        /// identifier and the audit timestamps are absent, because the first belongs to the row the
        /// tracker is holding and the second are the context's to stamp. Kept so the producer uses
        /// the same mapping as <see cref="ToModel"/> rather than a second, divergent one.
        /// </remarks>
        public void FromModel(StreamProblem model)
        {
            StreamId = model.StreamId;
            ErrorMessage = model.ErrorMessage;
        }
    }
}
