using Fluxy.Core.Persistence.Base;
using Fluxy.Core.Users.Models;

namespace Fluxy.DataAccess.Entities
{
    /// <summary>
    /// Database representation of one credit ledger entry. It is mutable, has no behaviour beyond
    /// mapping to <see cref="CreditLog"/>, and knows nothing about HTTP.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>The amount is the change, not the balance.</b> A row records how much credit one
    /// operation moved - positive for issuance, negative for spending - and never the running
    /// total, which lives on <c>users.credits</c>. A zero row is the entry an account created with
    /// no initial credit carries.
    /// </para>
    /// <para>
    /// <b><see cref="IssuedById"/> names every admin-panel row and is <c>ON DELETE SET NULL</c>.</b>
    /// A create and an update of either sign carry the acting administrator. Only a
    /// reseller-spent row has no issuer at all. When the issuing administrator's account is
    /// deleted, the history of the credit itself must survive, so the column is nulled rather than
    /// cascading the row away - unlike <see cref="ResellerId"/>, which cascades because a ledger
    /// line whose subject is gone is a line nobody can be told about.
    /// </para>
    /// </remarks>
    public sealed class CreditLogEntity : AuditableEntity
    {
        /// <summary>
        /// Initializes a new instance of the <see cref="CreditLogEntity"/> class for a row that is
        /// about to be inserted. The identifier is generated by the base class and both audit
        /// timestamps are stamped by the context.
        /// </summary>
        public CreditLogEntity()
        {
        }

        /// <summary>The reseller whose balance this row moved. Removed with the account.</summary>
        public Guid ResellerId { get; set; }

        /// <summary>
        /// Administrator who wrote this row in the admin panel, for a create or an update of
        /// either sign; null on a reseller-spent row and after the issuing administrator is
        /// deleted.
        /// </summary>
        public Guid? IssuedById { get; set; }

        /// <summary>Signed change to the balance.</summary>
        public int Amount { get; set; }

        /// <summary>English sentence describing the change.</summary>
        public string Description { get; set; } = string.Empty;

        /// <summary>Builds the business model out of this row.</summary>
        public CreditLog ToModel() => new()
        {
            Id = Id,
            ResellerId = ResellerId,
            IssuedById = IssuedById,
            Amount = Amount,
            Description = Description,
            CreatedAt = CreatedAt,
            UpdatedAt = UpdatedAt
        };
    }
}
