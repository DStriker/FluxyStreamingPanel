using Fluxy.Core.Persistence.Base;
using Fluxy.Core.Tickets.Models;

namespace Fluxy.DataAccess.Entities
{
    /// <summary>
    /// Database representation of one message in a support ticket conversation. It is mutable, has
    /// no behaviour beyond mapping to <see cref="TicketReply"/>, and knows nothing about HTTP.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>The ticket is a real foreign key that cascades.</b> A message without its conversation is
    /// unreadable, so closing the ticket's subject removes the thread with it.
    /// </para>
    /// <para>
    /// <b>The author is <c>SET NULL</c>, never cascade.</b> The message is part of the conversation:
    /// deleting the account that wrote it may make the author unknown, it may not remove what was
    /// said. <see cref="IsAdminReply"/> keeps the side legible without the author, which is why the
    /// side is stored rather than read from the account's current group.
    /// </para>
    /// <para>
    /// <b><see cref="ReadAt"/> is the per-message read mark.</b> The service sets it when the
    /// message's reader opens the thread; the column is the fact, and a null means the other side
    /// has not read it yet.
    /// </para>
    /// </remarks>
    public sealed class TicketReplyEntity : AuditableEntity
    {
        /// <summary>
        /// Initializes a new instance of the <see cref="TicketReplyEntity"/> class for a message
        /// that is about to be inserted. The identifier is generated by the base class and both
        /// audit timestamps are stamped by the context.
        /// </summary>
        public TicketReplyEntity()
        {
        }

        /// <summary>Ticket the message belongs to. Removed with it.</summary>
        public Guid TicketId { get; set; }

        /// <summary>Account that wrote it, or null once that account has been deleted.</summary>
        public Guid? AuthorId { get; set; }

        /// <summary>Message body, up to 4000 characters.</summary>
        public string Message { get; set; } = string.Empty;

        /// <summary>Whether the operator wrote it rather than the account.</summary>
        public bool IsAdminReply { get; set; }

        /// <summary>Moment the other side read it, or null while it is still unread.</summary>
        public DateTimeOffset? ReadAt { get; set; }

        /// <summary>Builds the business model out of this row.</summary>
        public TicketReply ToModel() => new()
        {
            Id = Id,
            TicketId = TicketId,
            AuthorId = AuthorId,
            Message = Message,
            IsAdminReply = IsAdminReply,
            ReadAt = ReadAt,
            CreatedAt = CreatedAt,
            UpdatedAt = UpdatedAt
        };

        /// <summary>
        /// Copies the changeable fields of the business model onto this row.
        /// </summary>
        /// <remarks>
        /// The identifier and the audit timestamps are absent, because the first belongs to the row
        /// the tracker is holding and the second are the context's to stamp.
        /// </remarks>
        public void FromModel(TicketReply model)
        {
            TicketId = model.TicketId;
            AuthorId = model.AuthorId;
            Message = model.Message;
            IsAdminReply = model.IsAdminReply;
            ReadAt = model.ReadAt;
        }
    }
}
