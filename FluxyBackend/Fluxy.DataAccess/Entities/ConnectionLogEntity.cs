using Fluxy.Core.Persistence.Base;
using Fluxy.Core.Subscriptions.Enums;
using Fluxy.Core.Subscriptions.Models;

namespace Fluxy.DataAccess.Entities
{
    /// <summary>
    /// Database representation of one streaming connection. It is mutable, has no behaviour
    /// beyond mapping to <see cref="ConnectionLog"/>, and knows nothing about HTTP.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>Country and provider are stored columns, and that is a deliberate divergence from the
    /// visit history.</b> The history resolves GeoIP while a page is being built because it stores
    /// no second copy of a fact the database could later answer differently. This table cannot
    /// take that route: the operator filters it by country and by provider, and a value that only
    /// exists during the request cannot be filtered or counted on the server. The snapshot is
    /// therefore taken when the session opens, and it stays as it was - it describes that session,
    /// not the network today. Nothing on the read path may call <c>IGeoIpResolver</c>: a lookup
    /// there would answer a different value from the one the filter ran against.
    /// </para>
    /// <para>
    /// <b>The subscription is a cascade foreign key.</b> A connection without the subscription it
    /// was made under is a row nobody can be told about, so deleting a subscription deletes its
    /// logs. That consequence is intended: the log is evidence about a subscription, and evidence
    /// whose subject is gone is what an operator asked to remove.
    /// </para>
    /// <para>
    /// <b>The stream identifier is opaque.</b> No foreign key points at <c>video_streams</c> or
    /// <c>audio_streams</c>: the relaying process may report a stream row this installation never
    /// recorded, exactly as <c>VideoStream.SeriesId</c> may name a series that was never recorded.
    /// The read path resolves the title when a row exists and answers null when it does not.
    /// </para>
    /// <para>
    /// <b>There is no duration.</b> <see cref="StartedAt"/> and <see cref="EndedAt"/> are the
    /// facts; subtracting one from the other is the reader's job.
    /// </para>
    /// </remarks>
    public sealed class ConnectionLogEntity : AuditableEntity
    {
        /// <summary>
        /// Initializes a new instance of the <see cref="ConnectionLogEntity"/> class for a row
        /// that is about to be inserted. The identifier is generated by the base class and both
        /// audit timestamps are stamped by the context.
        /// </summary>
        public ConnectionLogEntity()
        {
        }

        /// <summary>The subscription the connection was made under. Removed with it.</summary>
        public Guid SubscriptionId { get; set; }

        /// <summary>Which medium the connection delivered, as a <c>smallint</c>.</summary>
        public ConnectionStreamKind StreamKind { get; set; }

        /// <summary>Opaque identifier of the stream it delivered; deliberately not a foreign key.</summary>
        public Guid StreamId { get; set; }

        /// <summary>Address the session came from, up to 45 characters.</summary>
        public string Ip { get; set; } = string.Empty;

        /// <summary>User agent the session presented, or null.</summary>
        public string? UserAgent { get; set; }

        /// <summary>Upper-case ISO alpha-2 country of the address, or null when unknown.</summary>
        public string? CountryCode { get; set; }

        /// <summary>Internet provider the address belongs to, or null when unknown.</summary>
        public string? Isp { get; set; }

        /// <summary>When the session opened.</summary>
        public DateTimeOffset StartedAt { get; set; }

        /// <summary>When it finished, or null while it is still live.</summary>
        public DateTimeOffset? EndedAt { get; set; }

        /// <summary>Process identifier the broadcasting side reported, or null.</summary>
        public int? BroadcastPid { get; set; }

        /// <summary>Builds the business model out of this row.</summary>
        /// <remarks>
        /// <b>Reserved for the future capture path, which is why nothing calls it today.</b> The
        /// repository in this pass is read, clear and one insert intent the Development seeder
        /// uses, so no production read and no endpoint reaches this method. It stays beside
        /// <see cref="FromModel"/> because the write path that arrives with the relaying process
        /// will need the same pair every other entity here carries, and a mapping written then
        /// would be a second opinion about what the columns mean. It is deliberately not wired
        /// into a write path ahead of that caller.
        /// </remarks>
        public ConnectionLog ToModel() => new()
        {
            Id = Id,
            SubscriptionId = SubscriptionId,
            StreamKind = StreamKind,
            StreamId = StreamId,
            Ip = Ip,
            UserAgent = UserAgent,
            CountryCode = CountryCode,
            Isp = Isp,
            StartedAt = StartedAt,
            EndedAt = EndedAt,
            BroadcastPid = BroadcastPid,
            CreatedAt = CreatedAt,
            UpdatedAt = UpdatedAt
        };

        /// <summary>
        /// Copies the changeable fields of the business model onto this row.
        /// </summary>
        /// <remarks>
        /// <b>Reserved for the future capture path, which is why nothing calls it today.</b> The
        /// identifier and the audit timestamps are absent, because the first belongs to the row the
        /// tracker is holding and the second are the context's to stamp. No production endpoint and
        /// no read path reaches this method in this pass; it is kept so the capture that arrives
        /// with the relaying process uses the same mapping as <see cref="ToModel"/> rather than
        /// writing a second, divergent one.
        /// </remarks>
        public void FromModel(ConnectionLog model)
        {
            SubscriptionId = model.SubscriptionId;
            StreamKind = model.StreamKind;
            StreamId = model.StreamId;
            Ip = model.Ip;
            UserAgent = model.UserAgent;
            CountryCode = model.CountryCode;
            Isp = model.Isp;
            StartedAt = model.StartedAt;
            EndedAt = model.EndedAt;
            BroadcastPid = model.BroadcastPid;
        }
    }
}
