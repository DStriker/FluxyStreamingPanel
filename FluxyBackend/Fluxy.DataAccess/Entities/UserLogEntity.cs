using Fluxy.Core.Persistence.Base;
using Fluxy.Core.Users.Enums;
using Fluxy.Core.Users.Models;

namespace Fluxy.DataAccess.Entities
{
    /// <summary>
    /// Database representation of one user audit log entry. It is mutable, has no behaviour beyond
    /// mapping to <see cref="UserLog"/>, and knows nothing about HTTP.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>The outcome is a stored boolean, not a property of the record type.</b> The same kind of
    /// event ends either way, so <see cref="IsSuccess"/> is a column the writing flow fills in.
    /// </para>
    /// <para>
    /// <b><see cref="UserId"/> is <c>ON DELETE SET NULL</c>.</b> The log is evidence about what was
    /// attempted against an account, and deleting the account must not erase that evidence - it may
    /// only make the subject unknown. The row stays legible because the description already carries
    /// the identifier as it read at write time.
    /// </para>
    /// </remarks>
    public sealed class UserLogEntity : AuditableEntity
    {
        /// <summary>
        /// Initializes a new instance of the <see cref="UserLogEntity"/> class for a row that is
        /// about to be inserted. The identifier is generated by the base class and both audit
        /// timestamps are stamped by the context.
        /// </summary>
        public UserLogEntity()
        {
        }

        /// <summary>
        /// Account the entry is about, or null when the attempt named no existing account and after
        /// that account is deleted.
        /// </summary>
        public Guid? UserId { get; set; }

        /// <summary>Which kind of event the entry records, stored as a <c>smallint</c>.</summary>
        public UserLogRecordType RecordType { get; set; }

        /// <summary>Whether the attempt ended successfully.</summary>
        public bool IsSuccess { get; set; }

        /// <summary>English sentence describing the event.</summary>
        public string Description { get; set; } = string.Empty;

        /// <summary>Address the event came from, up to 45 characters, or null.</summary>
        public string? Ip { get; set; }

        /// <summary>Provider the address belonged to, or null.</summary>
        public string? Isp { get; set; }

        /// <summary>Upper-case ISO 3166-1 alpha-2 country of the address, or null.</summary>
        public string? CountryCode { get; set; }

        /// <summary>User agent the client presented, or null.</summary>
        public string? UserAgent { get; set; }

        /// <summary>Builds the business model out of this row.</summary>
        /// <remarks>
        /// <b>The endpoints that read the log project it straight into
        /// <see cref="UserLogListItem"/>, which is why nothing calls this today.</b> A page needs
        /// the account's current login name and its group, so it is assembled by a query rather
        /// than by mapping rows one at a time. The mapping stays beside the row so a caller that
        /// needs the whole model does not write a second, divergent opinion about what the columns
        /// mean.
        /// </remarks>
        public UserLog ToModel() => new()
        {
            Id = Id,
            UserId = UserId,
            RecordType = RecordType,
            IsSuccess = IsSuccess,
            Description = Description,
            Ip = Ip,
            Isp = Isp,
            CountryCode = CountryCode,
            UserAgent = UserAgent,
            CreatedAt = CreatedAt,
            UpdatedAt = UpdatedAt
        };
    }
}
